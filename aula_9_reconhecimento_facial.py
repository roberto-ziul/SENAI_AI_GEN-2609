import cv2
import face_recognition
from google.colab.patches import cv2_imshow # Renderizador para o Colab

# 1. CARREGAR A REFERÊNCIA (O cadastro no banco de dados)
print("[SISTEMA] Carregando imagem e gerando vetor de 128 números...")

# 2. A biblioteca carrega o arquivo e calcula a assinatura matemática (encoding)
foto_referencia = face_recognition.load_image_file("teste_desconhecido2.jpg")
encoding_referencia = face_recognition.face_encodings(foto_referencia)[0]

# 3. CARREGAR A FOTO DE TESTE (Pessoa tentando se identificar)
# Obs. Realizar o teste primeiro com o arquivo 'teste_sucesso.jpg
# e depois com 'teste_desconhecido.jpg'
imagem_analise = cv2.imread("teste_desconhecido2.jpg")

# 4. Conversão obrigatória: face_recognition lê em RGB, mas o OpenCV lê em BGR
imagem_analise_rgb = cv2.cvtColor(imagem_analise, cv2.COLOR_BGR2RGB)

# 5. Localizar o rosto na foto e extrair seus encodings
rosto_localizado = face_recognition.face_locations(imagem_analise_rgb)
encoding_do_rosto = face_recognition.face_encodings(imagem_analise_rgb, rosto_localizado)

for (topo, direita, fundo, esquerda), encoding_do_rosto_atual in \
  zip(rosto_localizado, encoding_do_rosto):

  # Calcular a distância matemática entra as duas assinaturas
  distancia = face_recognition.face_distance([encoding_referencia], encoding_do_rosto_atual)[0]
  print(f"\nDistância calculada entre os rostos: {distancia:.4f}")

  # Lógica de Threshold (Limite de tolerâcia de mercado = 0.6)
  if distancia < 0.6:
    label_texto = f"IDENTIFICADO ({100 - (distancia * 100):.1f}%)"
    cor_borda = (0, 255, 0) # Verde para sucesso
  else:
    label_texto = f"TESTUDO ({100 - (distancia * 100):.1f}%)"
    cor_borda = (0, 0, 255) # Vermelho para sucesso

  # Escrever feedback na tela com o OpenCV
  cv2.rectangle(imagem_analise, (esquerda, topo), (direita, fundo), cor_borda, 2)
  cv2.putText(imagem_analise, label_texto, (esquerda, topo - 10),
              cv2.FONT_HERSHEY_SIMPLEX, 0.6, cor_borda, 2)

# 6. Exibe o diagnóstico visual na tela
print("\n--- Resultado da Análise de Biometria Facial ---")
cv2_imshow(imagem_analise)

