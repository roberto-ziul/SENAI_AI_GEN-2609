def take_photo(label, img_data):
    data = eval_js(f'takePhoto("{label}", "{img_data}")')
    return data

"""### 0.3. Define Python functions"""

def js_response_to_image(js_response) -> Image.Image:
    _, b64_str = js_response['img'].split(',')
    jpeg_bytes = b64decode(b64_str)
    image = Image.open(io.BytesIO(jpeg_bytes))
    return image

def hide_black_pixels(rgb_compatible_array: np.ndarray) -> np.ndarray:
    alpha_channel = (rgb_compatible_array.max(axis=2) > 0).astype(np.uint8) * 255
    rgba_compatible_array = np.dstack((rgb_compatible_array, alpha_channel))
    return rgba_compatible_array

def black_rgb_canvas(h, w) -> np.ndarray:
    return np.zeros([h, w, 3], dtype=np.uint8)

def draw_annotations_on_transparent_bg(detection_result: Results) -> Image.Image:
    h, w = detection_result.orig_shape[:2]
    boxes_on_black_rgb_canvas = detection_result.plot(font='verdana', masks=False, img=black_rgb_canvas(h, w))
    boxes_on_transparent_rgba_canvas = hide_black_pixels(boxes_on_black_rgb_canvas)
    rgba_image = Image.fromarray(boxes_on_transparent_rgba_canvas)
    return rgba_image

"""## 1. Perform real-time object detection in webcam stream"""

start_stream()
img_data = ''
while True:
    js_response = take_photo('Capturing...', img_data)
    if not js_response:
        break
    captured_img = js_response_to_image(js_response)
    for detection_result in PRE_TRAINED_MODEL(source=np.array(captured_img), verbose=False):
        annotations_img = draw_annotations_on_transparent_bg(detection_result)
        with io.BytesIO() as buffer:
            annotations_img.save(buffer, format='png')
            img_as_base64_str = str(b64encode(buffer.getvalue()), 'utf-8')
            img_data = f'data:image/png;base64,{img_as_base64_str}'