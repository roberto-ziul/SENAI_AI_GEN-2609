import hashlib
import io
import time
from email.utils import parsedate_to_datetime

import numpy as np
import requests
from PIL import Image
from ultralytics import YOLO

try:
    from IPython.display import clear_output, display
    EM_COLAB = True
except ImportError:
    EM_COLAB = False


# =========================== CONFIGURACAO ===========================
PAGE_URL = "https://cameras.cetsp.com.br/View/Cam.aspx"
CAMERA_FOLDER = "31"
BASE_URL = f"https://cameras.cetsp.com.br/Cams/{CAMERA_FOLDER}"

PRIMEIRO_ARQUIVO = 1
ULTIMO_ARQUIVO = 50
INTERVALO_SEGUNDOS = 1.0

MODELO = "yolo26x.pt"
CONFIANCA = 0.35
TAMANHO_IMAGEM = 640
TIMEOUT = 15
MAX_FALHAS = 20
# ===================================================================


session = requests.Session()
session.headers.update({
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
        "AppleWebKit/537.36 (KHTML, like Gecko) "
        "Chrome/150.0 Safari/537.36"
    ),
    "Referer": PAGE_URL,
    "Accept": "image/avif,image/webp,image/apng,image/*,*/*;q=0.8",
    "Cache-Control": "no-cache",
    "Pragma": "no-cache",
})


def criar_sessao():
    """Abre a pagina principal para receber o cookie ASP.NET_SessionId."""
    resposta = session.get(PAGE_URL, timeout=TIMEOUT)
    resposta.raise_for_status()
    print("Sessao criada. Cookies:", session.cookies.get_dict())


def baixar_quadro(numero):
    """Baixa um JPEG do buffer, usando timestamp para impedir cache."""
    antcache = int(time.time() * 1000)
    url = f"{BASE_URL}/{numero}.jpg?{antcache}"

    resposta = session.get(url, timeout=TIMEOUT)
    if resposta.status_code != 200:
        return None

    if "image/jpeg" not in resposta.headers.get("Content-Type", "").lower():
        return None

    try:
        imagem = Image.open(io.BytesIO(resposta.content)).convert("RGB")
    except Exception:
        return None

    data_texto = resposta.headers.get("Last-Modified")
    try:
        data_modificacao = parsedate_to_datetime(data_texto) if data_texto else None
    except (TypeError, ValueError):
        data_modificacao = None

    return {
        "numero": numero,
        "url": url,
        "imagem": imagem,
        "etag": resposta.headers.get("ETag"),
        "hash": hashlib.sha256(resposta.content).hexdigest(),
        "data_modificacao": data_modificacao,
        "data_texto": data_texto,
    }


def localizar_quadro_mais_recente():
    """Examina o buffer uma vez e retorna o JPEG com Last-Modified mais recente."""
    encontrados = []
    print(f"Procurando o quadro mais recente entre 1 e {ULTIMO_ARQUIVO}...")

    for numero in range(PRIMEIRO_ARQUIVO, ULTIMO_ARQUIVO + 1):
        quadro = baixar_quadro(numero)
        if quadro is not None:
            encontrados.append(quadro)

    if not encontrados:
        raise RuntimeError(
            "Nenhuma imagem foi obtida. Verifique CAMERA_FOLDER, conexao, cookie ou bloqueio do Colab."
        )

    com_data = [q for q in encontrados if q["data_modificacao"] is not None]
    if com_data:
        return max(com_data, key=lambda q: q["data_modificacao"])

    return encontrados[-1]


def proximo_numero(numero):
    return PRIMEIRO_ARQUIVO if numero >= ULTIMO_ARQUIVO else numero + 1


def mostrar_resultado(resultado, quadro):
    """Exibe o quadro anotado no Colab; fora dele, salva uma imagem local."""
    anotada_bgr = resultado.plot()
    anotada_rgb = anotada_bgr[:, :, ::-1]
    imagem_saida = Image.fromarray(anotada_rgb)

    if EM_COLAB:
        clear_output(wait=True)
        print(f"Quadro: {quadro['numero']}.jpg")
        print(f"Last-Modified: {quadro['data_texto']}")
        print(f"Deteccoes: {len(resultado.boxes)}")
        display(imagem_saida)
    else:
        arquivo = "resultado_cet.jpg"
        imagem_saida.save(arquivo)
        print(f"Quadro {quadro['numero']}.jpg processado; resultado salvo em {arquivo}")


def executar():
    criar_sessao()
    modelo = YOLO(MODELO)

    inicial = localizar_quadro_mais_recente()
    numero = inicial["numero"]
    ultimo_hash = None
    falhas = 0

    print(f"Quadro inicial: {numero}.jpg")

    while True:
        quadro = baixar_quadro(numero)

        if quadro is None:
            falhas += 1
            if falhas >= MAX_FALHAS:
                raise RuntimeError("Numero maximo de falhas consecutivas atingido.")
            time.sleep(0.5)
            continue

        falhas = 0

        # Aguarda ate que o servidor publique conteudo novo nesse numero do buffer.
        if quadro["hash"] == ultimo_hash:
            time.sleep(0.25)
            continue

        frame = np.asarray(quadro["imagem"])
        resultado = modelo.predict(
            source=frame,
            conf=CONFIANCA,
            imgsz=TAMANHO_IMAGEM,
            verbose=False,
        )[0]

        mostrar_resultado(resultado, quadro)
        ultimo_hash = quadro["hash"]
        numero = proximo_numero(numero)
        time.sleep(INTERVALO_SEGUNDOS)


if __name__ == "__main__":
    try:
        executar()
    except KeyboardInterrupt:
        print("\nProcessamento interrompido pelo usuario.")
    except Exception as erro:
        print(f"\nErro: {erro}")
        raise