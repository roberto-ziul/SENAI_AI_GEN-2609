# CÉLULA 1: Coleta e criação de Base de dados
import pandas as pd

# 0 = E-mail Normal | 1 = SPAM
tabela_emails = pd.read_csv("base_emails_1000.csv")

print("Visualizando os primeiros e últimos e-mails da base de dados:")
display(tabela_emails)

# CÉLULA 2: Separando dados de Estudo e de Prova
from sklearn.model_selection import train_test_split

X = tabela_emails['Mensagem']
y = tabela_emails['Spam']

# Separando 20% (0.2) para o teste final
X_treino, X_teste, y_treino, y_teste = \
train_test_split(X, y, test_size=0.1, random_state=42, stratify=y)

print(f"E-mails para treinar: {len(X_treino)}")
print(f"E-mails escondidos para a prova: {len(X_teste)}")

# CÉLULA 3: Pré-processamento (Vetorização)
from sklearn.feature_extraction.text import CountVectorizer

# Cria o nosso tradutor de textos para números
tradutor = CountVectorizer()

# Ensina o tradutor com os textos de treino e faz a tradução
X_treino_numeros = tradutor.fit_transform(X_treino)

# Traduz também os textos da prova
X_teste_numeros = tradutor.transform(X_teste)

print("O ML não lê texto, ele lê matrizes assim:")
print(X_treino_numeros.toarray())

#pd.set_option("display,max_rows", None)
#

# CÉLULA 4: Treinar e avaliar o modelo (Árvore de Des)
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score

# 1. Criar nosso Classificador
modelo_spam = DecisionTreeClassifier(max_depth=3, random_state=42)

modelo_spam.fit(X_treino_numeros, y_treino)

precisoes = modelo_spam.predict(X_teste_numeros)

nota = accuracy_score(y_teste, precisoes)
print(f"Taxa de acerto do modelo: {nota * 100}%!")

# CÉLULA 5: O filtro em ação
nova_mensagem = ['']

# 1. Traduzir o email novo para matemática
nova_mensagem_numeros = tradutor.transform(nova_mensagem)

# 2. Pedir para a IA classificar
resultado = modelo_spam.predict(nova_mensagem_numeros)

if resultado[0] == 1:
  print("ALERTA: Mensagem classificada como SPAM!")
else:
  print("SEGURO: Mensagem classificada como Normal!")