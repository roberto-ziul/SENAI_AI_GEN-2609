# EXECUÇÃO INTEGRADA: spaCy + NLTK

print(f"{'FEEDBACK ORIGINAL':<70} | {'NOTA':<6} | {'SENTIMENTO'}")
print("_" * 90)

for texto in frases_clientes:
  texto_minusculo = texto.lower()
  doc = nlp(texto_minusculo)
  palavras_uteis = []

  for token in doc:
    if token.is_punct:
      continue
    if token.is_stop and token.text not in ["não", "nunca", "jamais"]:
      continue
    palavras_uteis.append(token.lemma_)
  print("Palavras utéis:", palavras_uteis)

  frase_limpa = " ".join(palavras_uteis)
  nota = termometro_nltk.polarity_scores(frase_limpa)['compound']

  if nota >= 0.1:
    resultado = "😆 POSITIVO"
  elif nota <= -0.1:
    resultado = "🤬 NEGATIVO"
  else:
    resultado = " NEUTRO"

  print(f"{texto:<70} | {nota:<6.1f} | {resultado}\n")